def _platform_float_tolerance(path_parts: tuple[str, ...]) -> tuple[float, float] | None:
    """Return `(abs_floor, rel_tol)` if `path_parts` is an allowlisted 2D `spsolve` float output, else `None` (exact `==`)."""
    # Strip trailing list-index markers (`[0]`, `[12]`, etc.) to find the owning field key and parent context.
    non_index = [p for p in path_parts if not p.startswith("[")]
    if len(non_index) < 2:
        return None
    leaf = non_index[-1]
    parent = non_index[-2]
    grandparent = non_index[-3] if len(non_index) >= 3 else ""

    # Never allow tolerance on invariant subtrees even if a future key collides
    if any(seg in ("constants", "parameters", "metadata", "provenance", "thresholds", "reference_1d") for seg in non_index):
        return None

    if leaf in _PLATFORM_DEPENDENT_2D_EFIELD_LEAVES:
        if parent in ("solution", "probe") or (parent == "rows" and grandparent == "probe_study"):
            # Finite-difference E-field has ~1e-10 V / h (~2.5e-7 V/m) cross-platform SuperLU roundoff on symmetry-zero points.
            return (1e-6, 1e-8)
        return None

    if parent == "solution" and leaf in _PLATFORM_DEPENDENT_2D_FLOAT_LEAVES["solution"]:
        return (1e-9, 1e-8)
    if parent == "probe" and leaf in _PLATFORM_DEPENDENT_2D_FLOAT_LEAVES["probe"]:
        return (1e-9, 1e-8)
    if parent == "force_budget" and leaf in _PLATFORM_DEPENDENT_2D_FLOAT_LEAVES["force_budget"]:
        return (1e-9, 1e-8)
    if parent == "rows" and grandparent == "force_study" and leaf in _PLATFORM_DEPENDENT_2D_FLOAT_LEAVES["force_study_rows"]:
        return (1e-9, 1e-8)
    if grandparent == "component_assessments" and leaf in _PLATFORM_DEPENDENT_2D_FLOAT_LEAVES["component_assessments"]:
        return (1e-9, 1e-8)
    if parent == "derived_sensitivity" and leaf in _PLATFORM_DEPENDENT_2D_FLOAT_LEAVES["derived_sensitivity"]:
        return (1e-9, 1e-8)
    if parent == "per_component_last_step_diff_n_per_m" and leaf in _PLATFORM_DEPENDENT_2D_FLOAT_LEAVES["per_component_last_step_diff_n_per_m"]:
        return (1e-9, 1e-8)
    if parent == "rows" and grandparent == "probe_study" and leaf in _PLATFORM_DEPENDENT_2D_FLOAT_LEAVES["probe_study_rows"]:
        return (1e-9, 1e-8)
    if parent == "assessment" and grandparent == "probe_study" and leaf in _PLATFORM_DEPENDENT_2D_FLOAT_LEAVES["probe_study_assessment"]:
        return (1e-9, 1e-8)
    return None


def _compare_snapshot_bundles(obj_a: Any, obj_b: Any, path_parts: tuple[str, ...] = ("root",)) -> None:
    """Compare committed vs freshly generated snapshot bundles with strict invariant equality."""
    path_label = ".".join(path_parts)
    if type(obj_a) is not type(obj_b):
        raise ValueError(f"Type mismatch at {path_label}: {type(obj_a).__name__} vs {type(obj_b).__name__}")

    if isinstance(obj_a, dict):
        keys_a = list(obj_a.keys())
        keys_b = list(obj_b.keys())
        if keys_a != keys_b:
            raise ValueError(f"Key order/set mismatch at {path_label}: {keys_a} vs {keys_b}")
        for k in keys_a:
            _compare_snapshot_bundles(obj_a[k], obj_b[k], path_parts + (str(k),))
        return

    if isinstance(obj_a, list):
        if len(obj_a) != len(obj_b):
            raise ValueError(f"Length mismatch at {path_label}: {len(obj_a)} vs {len(obj_b)}")
        for idx, (va, vb) in enumerate(zip(obj_a, obj_b)):
            _compare_snapshot_bundles(va, vb, path_parts + (f"[{idx}]",))
        return

    if isinstance(obj_a, float):
        tol_spec = _platform_float_tolerance(path_parts)
        if tol_spec is None:
            if obj_a != obj_b:
                raise ValueError(f"Invariant float mismatch at {path_label}: {obj_a!r} != {obj_b!r}")
            return
        abs_floor, rel_tol = tol_spec
        tol = max(abs_floor, rel_tol * max(abs(obj_a), abs(obj_b)))
        if abs(obj_a - obj_b) > tol:
            raise ValueError(
                f"2D solver float drift exceeds tolerance ({tol:.3e}) at {path_label}: {obj_a!r} vs {obj_b!r}"
            )
        return

    if isinstance(obj_a, str) and obj_a != obj_b:
        leaf = path_parts[-1]
        if leaf in ("diagnostic_note", "discrete_closure_verdict", "assessment_summary"):
            nums_a = [float(x) for x in _SCI_NUM_RE.findall(obj_a)]
            nums_b = [float(x) for x in _SCI_NUM_RE.findall(obj_b)]
            masked_a = _SCI_NUM_RE.sub("<NUM>", obj_a)
            masked_b = _SCI_NUM_RE.sub("<NUM>", obj_b)
            if masked_a != masked_b or len(nums_a) != len(nums_b):
                raise ValueError(f"Diagnostic narrative structure mismatch at {path_label}")
            for na, nb in zip(nums_a, nums_b):
                tol = max(1e-9, 1e-5 * max(abs(na), abs(nb)))
                if abs(na - nb) > tol:
                    raise ValueError(f"Diagnostic narrative float drift at {path_label}: {na!r} vs {nb!r}")
            return
        raise ValueError(f"String mismatch at {path_label}: {obj_a!r} != {obj_b!r}")

    if obj_a != obj_b:
        raise ValueError(f"Value mismatch at {path_label}: {obj_a!r} != {obj_b!r}")


def render_js_from_json_payload(json_payload: str) -> str:
    """Embed a canonical JSON payload string into the deterministic LF JS runtime template."""
    js_content = JS_RUNTIME_HELPERS_TEMPLATE.replace("__SNAPSHOT_JSON_PAYLOAD__", json_payload)
    if "\r" in js_content:
        raise ValueError("Rendered JS artifact contains forbidden CR characters")
    return js_content


def render_snapshot_artifacts(
    bundle: dict[str, Any],
) -> tuple[str, str]:
    """Render deterministic LF JSON and JS artifact text from `bundle`."""
    json_payload = adapter.strict_rfc8259_dumps(bundle)
    if "\r" in json_payload:
        raise ValueError("Rendered JSON payload contains forbidden CR characters")
    js_content = render_js_from_json_payload(json_payload)
    return json_payload + "\n", js_content


def render_snapshot_artifact_bytes(
    bundle: dict[str, Any],
) -> tuple[bytes, bytes]:
    """Render deterministic UTF-8 LF raw bytes for both JSON and JS snapshot artifacts."""
    json_text, js_text = render_snapshot_artifacts(bundle)
    return json_text.encode("utf-8"), js_text.encode("utf-8")


def write_snapshot_artifacts(
    *,
    js_out: Path = DEFAULT_JS_OUT,
    json_out: Path = DEFAULT_JSON_OUT,
    source_head_sha: str = FROZEN_B1_ACCEPTED_SOURCE_SHA,
) -> dict[str, str]:
    """Generate and write deterministic raw UTF-8 LF JSON and JS snapshot artifacts to disk."""
    bundle = build_reference_snapshot_bundle(source_head_sha=source_head_sha)
    json_bytes, js_bytes = render_snapshot_artifact_bytes(bundle)
    json_out.write_bytes(json_bytes)
    js_out.write_bytes(js_bytes)
    return {
        "json_sha256": hashlib.sha256(json_bytes).hexdigest(),
        "js_sha256": hashlib.sha256(js_bytes).hexdigest(),
    }


def verify_committed_snapshot_artifacts(
    *,
    js_path: Path = DEFAULT_JS_OUT,
    json_path: Path = DEFAULT_JSON_OUT,
    source_head_sha: str = FROZEN_B1_ACCEPTED_SOURCE_SHA,
    fresh_bundle: dict[str, Any] | None = None,
) -> None:
    """Verify committed JS/JSON snapshot fidelity: raw LF bytes, exact JS/JSON parity, exact invariants, and tight 2D solver parity."""
    if not json_path.exists() or not js_path.exists():
        raise FileNotFoundError(f"Snapshot artifacts missing on disk: json={json_path}, js={js_path}")

    disk_json_bytes = json_path.read_bytes()
    disk_js_bytes = js_path.read_bytes()

    if b"\r" in disk_json_bytes:
        raise ValueError(f"Committed JSON artifact contains forbidden CR bytes (CRLF): {json_path}")
    if b"\r" in disk_js_bytes:
        raise ValueError(f"Committed JS artifact contains forbidden CR bytes (CRLF): {js_path}")
    if not disk_json_bytes.endswith(b"\n"):
        raise ValueError(f"Committed JSON artifact missing trailing LF newline: {json_path}")

    disk_json_text = disk_json_bytes.decode("utf-8")
    disk_bundle = json.loads(disk_json_text)
    canonical_disk_json_bytes = (adapter.strict_rfc8259_dumps(disk_bundle) + "\n").encode("utf-8")
    if disk_json_bytes != canonical_disk_json_bytes:
        raise ValueError(f"Committed JSON artifact is not canonical RFC 8259 bytes: {json_path}")

    # Enforce exact byte-for-byte parity between committed JS and (JS template + committed JSON payload)
    expected_disk_js_bytes = render_js_from_json_payload(disk_json_text[:-1]).encode("utf-8")
    if disk_js_bytes != expected_disk_js_bytes:
        raise ValueError(
            f"Committed JS artifact {js_path} diverges from generator template or committed JSON payload {json_path}"
        )

    # Compare committed bundle against freshly generated bundle (exact for all invariants; tight allowlisted tolerances for 2D spsolve)
    target_bundle = (
        fresh_bundle if fresh_bundle is not None else build_reference_snapshot_bundle(source_head_sha=source_head_sha)
    )
    _compare_snapshot_bundles(disk_bundle, target_bundle)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Generate V1 offline reference snapshots (V1-B Slice B2).")
    parser.add_argument("--js-out", type=Path, default=DEFAULT_JS_OUT, help="Output path for v1_reference_snapshots.js")
    parser.add_argument(
        "--json-out", type=Path, default=DEFAULT_JSON_OUT, help="Output path for v1_reference_snapshots.json"
    )
    parser.add_argument(
        "--source-head-sha",
        type=str,
        default=FROZEN_B1_ACCEPTED_SOURCE_SHA,
        help="Deterministic accepted source HEAD SHA recorded in snapshot provenance.",
    )
    mode_group = parser.add_mutually_exclusive_group()
    mode_group.add_argument(
        "--check",
        action="store_true",
        help="Verify on-disk artifacts match current-platform deterministic output byte-for-byte (raw bytes, no CRLF normalization).",
    )
    mode_group.add_argument(
        "--check-committed",
        action="store_true",
        help=(
            "Verify committed JS/JSON artifacts: raw LF bytes, exact byte-for-byte JS/JSON/template parity, "
            "exact equality on all constants/provenance/schema/fingerprints/1D values, and tight cross-platform 2D spsolve parity."
        ),
    )
    args = parser.parse_args(argv)

    if args.check_committed:
        try:
            verify_committed_snapshot_artifacts(
                js_path=args.js_out,
                json_path=args.json_out,
                source_head_sha=args.source_head_sha,
            )
        except Exception as exc:  # noqa: BLE001
            sys.stderr.write(f"ERROR: Committed snapshot fidelity gate failed: {exc}\n")
            return 1
        sys.stdout.write("Committed V1 reference snapshots fidelity gate passed.\n")
        return 0

    bundle = build_reference_snapshot_bundle(source_head_sha=args.source_head_sha)
    json_bytes, js_bytes = render_snapshot_artifact_bytes(bundle)

    if args.check:
        if not args.json_out.exists() or not args.js_out.exists():
            sys.stderr.write("ERROR: Snapshot artifacts missing on disk.\n")
            return 1
        disk_json_bytes = args.json_out.read_bytes()
        disk_js_bytes = args.js_out.read_bytes()
        if disk_json_bytes != json_bytes or disk_js_bytes != js_bytes:
            sys.stderr.write("ERROR: On-disk snapshot artifacts differ byte-for-byte from deterministic generator output.\n")
            return 1
        return 0

    args.json_out.write_bytes(json_bytes)
    args.js_out.write_bytes(js_bytes)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
